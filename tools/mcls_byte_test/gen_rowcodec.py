#!/usr/bin/env python3
"""tools/mcls_byte_test/gen_rowcodec.py <Serialization.cpp> <out.inc>

Copies THE gambit-row codec out of native/Serialization.cpp, text for text, so the host test compiles the game's own
row encoding and never a hand mirror: the four templates WriteOpT / ReadOpT / WriteRowT / ReadRowT (they live in that
file's anonymous namespace, which cannot be linked) and the five GambitWire forwarders. Fails loudly when a function
is not found, so a rename in Serialization.cpp breaks this test instead of silently testing an old copy."""
import sys

src = open(sys.argv[1], encoding="utf-8").read()


def body_from(start):
    """The text from `start` to the brace that closes the first '{' after it."""
    i = src.index("{", start)
    depth = 0
    while True:
        c = src[i]
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                return src[start:i + 1]
        i += 1


def template(name):
    at = src.find("bool " + name + "(")
    if at < 0:
        sys.exit(f"gen_rowcodec: '{name}' not found in {sys.argv[1]}")
    start = src.rfind("template <class", 0, at)
    if start < 0 or src[start:at].count("\n") > 2:
        sys.exit(f"gen_rowcodec: no template header right above '{name}'")
    return body_from(start)


def forwarders():
    out, at = [], 0
    while True:
        at = src.find("    bool GambitWire::", at)
        if at < 0:
            break
        text = body_from(at)
        out.append(text)
        at += len(text)
    if len(out) != 5:
        sys.exit(f"gen_rowcodec: expected 5 GambitWire forwarders, found {len(out)}")
    return out


parts = ["// GENERATED by tools/mcls_byte_test/gen_rowcodec.py from native/Serialization.cpp. Do not edit.",
         "namespace MFO {", "    namespace {",
         "        constexpr std::uint32_t kMaxOpcodeLen = GambitWire::kMaxOpcodeLen;"]
parts += ["        " + template(n) for n in ("WriteOpT", "ReadOpT", "WriteRowT", "ReadRowT")]
parts += ["    }"] + forwarders() + ["}", ""]
open(sys.argv[2], "w", encoding="utf-8").write("\n\n".join(parts))
