#!/usr/bin/env python3
"""iaus_sim/gen_vocab.py -- write the HOST subset of native/Vocabulary.h the class table needs (run by run.sh).

The real header pulls in engine types. The class table (native/classes/ClassTable.cpp) only uses the opcode string
constants and the Subject enum, so this copies exactly those lines out of the real file. Nothing is retyped: a
renamed or removed opcode still breaks the simulator's build, as it breaks the game's.

usage: gen_vocab.py <native/Vocabulary.h> <out/Vocabulary.h>
"""
import re, sys

src = open(sys.argv[1], encoding='utf-8', errors='replace').read()
m = re.search(r'enum class Subject\b.*?\n    \};', src, re.S)
if not m: sys.exit('gen_vocab: Subject enum not found')
consts = re.findall(r'^\s*inline constexpr const char\*\s+k\w+\s*=\s*"[^"]*";', src, re.M)
if len(consts) < 40: sys.exit('gen_vocab: opcode constants not found')
out = ['#pragma once', '// GENERATED by tools/iaus_sim/gen_vocab.py from native/Vocabulary.h. Do not edit.', '#include <cstdint>', '',
       'namespace MFO::Vocab {', '    ' + m.group(0).strip()] + ['    ' + c.strip() for c in consts] + ['}', '']
open(sys.argv[2], 'w').write('\n'.join(out))
